/**
 * Regenerate src/client/provider-marks.ts from Lobe Icons' SVG files.
 *
 *   npm pack @lobehub/icons-static-svg@1.102.0   # in an empty temporary directory
 *   tar -xzf lobehub-icons-static-svg-1.102.0.tgz
 *   node scripts/provider-marks.ts <that directory>/package/icons
 *
 * Takes `<name>-color.svg` when it exists, else `<name>.svg`, for every name in
 * ICON_NAMES. The SVG body is kept as is; only the title is dropped and
 * gradient ids become a placeholder the component fills per instance.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ICON_NAMES } from '../src/shared/icons.ts'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node scripts/provider-marks.ts <@lobehub/icons-static-svg>/package/icons')
const root = dirname(dirname(fileURLToPath(import.meta.url)))

const entries = ICON_NAMES.map((name) => {
  const file = existsSync(join(dir, `${name}-color.svg`)) ? `${name}-color.svg` : `${name}.svg`
  const svg = readFileSync(join(dir, file), 'utf8')
  const open = /^<svg([^>]*)>/.exec(svg)
  if (!open || !svg.endsWith('</svg>')) throw new Error(`${file}: not a single <svg> element`)
  const attribute = (key: string) => new RegExp(`\\s${key}="([^"]*)"`).exec(open[1]!)?.[1]
  if (attribute('viewBox') !== '0 0 24 24') throw new Error(`${file}: viewBox is not 0 0 24 24`)
  let body = svg.slice(open[0].length, -'</svg>'.length).replace(/<title>[^<]*<\/title>/, '')
  ;[...body.matchAll(/\sid="([^"]+)"/g)].forEach(([, id], index) => {
    body = body.replaceAll(`id="${id}"`, `id="__ID__-${index}"`).replaceAll(`url(#${id})`, `url(#__ID__-${index})`)
  })
  const fill = attribute('fill')
  const rule = attribute('fill-rule')
  return [
    `  ${JSON.stringify(name)}: {`,
    `    file: ${JSON.stringify(file)},`,
    ...(fill ? [`    fill: ${JSON.stringify(fill)},`] : []),
    ...(rule ? [`    rule: ${JSON.stringify(rule)},`] : []),
    `    body: ${JSON.stringify(body)},`,
    '  },',
  ].join('\n')
})

writeFileSync(
  join(root, 'src/client/provider-marks.ts'),
  `/*! Lobe Icons (@lobehub/icons-static-svg 1.102.0), MIT.
 * Copyright (c) 2023 LobeHub. Full license and source attribution in README.md.
 * SVG bodies of the files named below, unchanged except for the dropped title and gradient ids.
 */
// Generated by scripts/provider-marks.ts; do not edit.
import type { IconName } from '../shared/icons.ts'

export interface Mark {
  file: string
  fill?: string
  rule?: 'evenodd' | 'nonzero'
  /** SVG markup inside a 24×24 viewBox; \`__ID__\` stands for an id unique to the rendered instance. */
  body: string
}

export const MARKS: Record<IconName, Mark> = {
${entries.join('\n')}
}
`,
)
console.log(`provider-marks: ${ICON_NAMES.length} marks`)
